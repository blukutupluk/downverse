#!/data/data/com.termux/files/usr/bin/bash
# Threads backend: Debian Chromium/Playwright capture; Termux curl + ffprobe + ffmpeg.
module_threads() {
  local mode="${1:-video}"
  local out="$THREADS_OUTPUT" cookie="$THREADS_COOKIE" url stamp work manifest rc
  if [[ "$mode" == "carousel" ]]; then out="$THREADS_OUTPUT/Carousel"; fi
  local -a stream_items=() image_items=()
  local item kind mime media_url idx=1 tmpfile has_v has_a duration

  mkdir -p "$out" || { ui_error "Tidak bisa membuat output: $out"; ui_pause; return 1; }
  ui_header
  if [[ "$mode" == "carousel" ]]; then
    ui_section "THREADS CAROUSEL / SEMUA MEDIA"
    ui_warn "Mode ini memang mengambil gambar dan video dari item carousel."
  else
    ui_section "THREADS VIDEO SAJA"
    ui_ok "Mode video: satu post, tanpa klik carousel dan tanpa download gambar."
  fi
  ask_url "Threads URL" || { ui_pause; return 1; }
  url="$URL"

  for c in curl ffmpeg ffprobe python; do
    command -v "$c" >/dev/null 2>&1 || { ui_error "Dependency Termux tidak ada: $c"; ui_pause; return 1; }
  done
  proot_require || { ui_pause; return 1; }
  [[ -f "$cookie" ]] || { ui_error "Cookie Threads tidak ditemukan: $cookie"; ui_warn "Ekspor cookies Netscape ke ~/cookies/threads.txt dahulu."; ui_pause; return 1; }
  proot_login test -x "$PROOT_PYTHON" >/dev/null 2>&1 || { ui_error "Python venv Debian belum siap. Jalankan fish $INSTALLER"; ui_pause; return 1; }

  stamp="$(date +%Y%m%d_%H%M%S)"
  work="$out/.threads_work_$stamp"
  manifest="$work/capture.json"
  mkdir -p "$work" || { ui_error "Tidak bisa membuat temporary directory."; ui_pause; return 1; }

  printf '\n%b\n' "${DIM}Membuka Threads dengan Chromium + Playwright...${RESET}"
  proot_login "$PROOT_PYTHON" \
    "$BASE_DIR/downloader/backend/threads_capture.py" \
    --cookie "$cookie" --url "$url" --out "$manifest" --mode "$mode"
  rc=$?
  if [[ $rc -ne 0 || ! -s "$manifest" ]]; then
    ui_error "Capture browser gagal (exit $rc)."
    rm -rf "$work"; ui_pause; return 1
  fi

  printf '%b\n' "${GREEN}Manifest media berhasil dibuat.${RESET}"
  printf '%s\n' "${DIM}Target: $(python -c 'import json,sys; print(json.load(open(sys.argv[1])).get("final_url",""))' "$manifest" 2>/dev/null)${RESET}"

  # Parse manifest generated by Debian browser. URL is kept intact apart from
  # byte-range query parameters already removed by the capture backend.
  while IFS=$'\t' read -r kind mime media_url; do
    [[ -z "$media_url" ]] && continue
    case "$kind" in
      image)
        [[ "$mode" == "carousel" ]] && image_items+=("$mime|$media_url")
        ;;
      video|audio|unknown) stream_items+=("$kind|$mime|$media_url") ;;
    esac
  done < <(python -c 'import json,sys; d=json.load(open(sys.argv[1])); [print(x.get("kind","unknown"),x.get("mime",""),x.get("url",""),sep="\t") for x in d.get("media",[])]' "$manifest")

  if [[ ${#stream_items[@]} -eq 0 && ${#image_items[@]} -eq 0 ]]; then
    if [[ "$mode" == "video" ]]; then
      ui_error "Stream video/audio untuk post ini tidak ditemukan. Tidak ada gambar yang akan diunduh sebagai pengganti."
    else
      ui_error "Tidak ada media yang tertangkap dari carousel."
    fi
    printf '%b\n' "${DIM}Response browser: $(python -c 'import json,sys; print(json.load(open(sys.argv[1])).get("diagnostics",{}))' "$manifest")${RESET}"
    rm -rf "$work"; ui_pause; return 1
  fi

  # Download image assets. Extension is inferred from response MIME / URL path.
  for item in "${image_items[@]}"; do
    local ext
    IFS='|' read -r mime media_url <<< "$item"
    case "$mime" in
      image/png*) ext="png" ;;
      image/webp*) ext="webp" ;;
      image/jpeg*) ext="jpg" ;;
      *) ext="$(python -c 'import sys,urllib.parse; u=sys.argv[1]; e=urllib.parse.urlsplit(u).path.rsplit(".",1)[-1].lower(); print(e if e in ("jpg","jpeg","png","webp") else "jpg")' "$media_url")" ;;
    esac
    tmpfile="$out/threads_${stamp}_img_$(printf '%03d' "$idx").$ext"
    printf '%b\n' "${CYAN}Download image #$idx...${RESET}"
    if curl -L --fail --retry 3 --retry-delay 2 --connect-timeout 20 \
      -A "Mozilla/5.0 (Linux; Android 16)" -H 'Referer: https://www.threads.com/' \
      -o "$tmpfile" "$media_url" && [[ -s "$tmpfile" ]]; then
      ui_ok "Image #$idx tersimpan."
    else
      rm -f "$tmpfile"; ui_warn "Image #$idx gagal diunduh."
    fi
    ((idx++))
  done

  local sidx=1 stream_kind stream_mime stream_url
  local -a downloaded=() video_paths=() audio_paths=() muxed_paths=()
  for item in "${stream_items[@]}"; do
    IFS='|' read -r stream_kind stream_mime stream_url <<< "$item"
    tmpfile="$work/stream_$(printf '%03d' "$sidx").mp4"
    printf '%b\n' "${CYAN}Download stream #$sidx ($stream_kind)...${RESET}"
    if curl -L --fail --retry 3 --retry-delay 2 --connect-timeout 20 \
      -A "Mozilla/5.0 (Linux; Android 16)" -H 'Referer: https://www.threads.com/' \
      -o "$tmpfile" "$stream_url" && [[ -s "$tmpfile" ]]; then
      has_v=0; has_a=0
      ffprobe -v error -select_streams v:0 -show_entries stream=codec_type -of csv=p=0 "$tmpfile" 2>/dev/null | grep -q '^video$' && has_v=1
      ffprobe -v error -select_streams a:0 -show_entries stream=codec_type -of csv=p=0 "$tmpfile" 2>/dev/null | grep -q '^audio$' && has_a=1
      if [[ $has_v -eq 1 && $has_a -eq 1 ]]; then muxed_paths+=("$tmpfile")
      elif [[ $has_v -eq 1 ]]; then video_paths+=("$tmpfile")
      elif [[ $has_a -eq 1 ]]; then audio_paths+=("$tmpfile")
      else rm -f "$tmpfile"; ui_warn "Stream #$sidx bukan audio/video valid."; fi
    else
      rm -f "$tmpfile"; ui_warn "Stream #$sidx gagal diunduh."
    fi
    ((sidx++))
  done

  # Already-muxed media can be remuxed directly; separated tracks are paired
  # only when there is one unambiguous match or equal track counts.
  local final_idx=1 video_path audio_path outfile
  for video_path in "${muxed_paths[@]}"; do
    outfile="$out/threads_${stamp}_video_$(printf '%02d' "$final_idx").mp4"
    if ffmpeg -hide_banner -loglevel error -y -i "$video_path" -map 0:v:0 -map 0:a? -c:v copy -c:a aac -b:a 160k -movflags +faststart "$outfile"; then
      ui_ok "Video muxed tersimpan: $(basename "$outfile")"
    else
      ui_warn "Remux gagal; mempertahankan stream asli."
      cp -f "$video_path" "$outfile"
    fi
    ((final_idx++))
  done

  local acount=${#audio_paths[@]} vcount=${#video_paths[@]}
  local vduration aduration diff bestdiff best_index ai
  local -a used_audio=()
  for video_path in "${video_paths[@]}"; do
    audio_path=""
    best_index=-1
    bestdiff=""
    if [[ $acount -eq 1 && $vcount -eq 1 ]]; then
      audio_path="${audio_paths[0]}"; used_audio[0]=1
    elif [[ $acount -gt 0 ]]; then
      vduration="$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$video_path" 2>/dev/null)"
      for ((ai=0; ai<acount; ai++)); do
        [[ -n "${used_audio[$ai]:-}" ]] && continue
        aduration="$(ffprobe -v error -show_entries format=duration -of csv=p=0 "${audio_paths[$ai]}" 2>/dev/null)"
        [[ -n "$vduration" && -n "$aduration" ]] || continue
        diff="$(awk -v v="$vduration" -v a="$aduration" 'BEGIN {d=v-a; if(d<0)d=-d; printf "%.6f", d}')"
        if [[ -z "$bestdiff" ]] || awk -v a="$diff" -v b="$bestdiff" 'BEGIN {exit !(a < b)}'; then
          bestdiff="$diff"
          best_index=$ai
        fi
      done
      # Jangan pasangkan audio yang durasinya sangat berbeda.
      if [[ $best_index -ge 0 ]] && awk -v d="$bestdiff" 'BEGIN {exit !(d <= 3.0)}'; then
        audio_path="${audio_paths[$best_index]}"
        used_audio[$best_index]=1
      fi
    fi

    outfile="$out/threads_${stamp}_video_$(printf '%02d' "$final_idx").mp4"
    if [[ -n "$audio_path" ]]; then
      if ffmpeg -hide_banner -loglevel error -y -i "$video_path" -i "$audio_path" \
        -map 0:v:0 -map 1:a:0 -c:v copy -c:a aac -b:a 160k -shortest -movflags +faststart "$outfile"; then
        ui_ok "Video #$final_idx selesai dengan audio."
      else
        rm -f "$outfile"; cp -f "$video_path" "$outfile"
        ui_warn "Merge gagal untuk video #$final_idx; video disimpan tanpa audio."
      fi
    else
      cp -f "$video_path" "$outfile"
      ui_warn "Tidak ada pasangan audio yang tidak ambigu untuk video #$final_idx."
    fi
    ((final_idx++))
  done

  rm -rf "$work"
  printf '\n%b\n' "${GREEN}${BOLD}Threads selesai diproses.${RESET}"
  if [[ "$mode" == "video" ]]; then
    printf '%b\n' "${DIM}Mode: video saja (satu post). Gambar/thumbnail tidak diunduh.${RESET}"
  else
    printf '%b\n' "${DIM}Mode: carousel (semua media yang berhasil ditangkap).${RESET}"
  fi
  printf '%b\n' "${DIM}Output: $out${RESET}"
  if [[ ${#image_items[@]} -gt 0 ]]; then printf '%b\n' "${DIM}Gambar tertangkap: ${#image_items[@]}${RESET}"; fi
  if [[ ${#stream_items[@]} -gt 0 ]]; then printf '%b\n' "${DIM}Stream video/audio tertangkap: ${#stream_items[@]}${RESET}"; fi
  ui_pause
}
